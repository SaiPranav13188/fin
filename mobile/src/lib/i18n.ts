/** Translate a piece of UI text into the language chosen in settings. */
export function t(text: string): string {
  const lang = useStore.getState().settings.lang;
  if (lang === 'en') return text;
  const row = DICT[text];
  return row ? row[lang === 'hi' ? 0 : 1] : text;
}
